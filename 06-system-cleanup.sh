#!/bin/bash
# =============================================================================
# Debian 13 Server - Очистка системы
# =============================================================================
# Описание: Очистка кэша, логов, временных файлов
# Версия: 1.0
# =============================================================================

set -e
set -u

# =============================================================================
# ЦВЕТНОЙ ВЫВОД
# =============================================================================
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
WHITE='\033[1;37m'
PURPLE='\033[0;35m'
NC='\033[0m'

log_info() { echo -e "${GREEN}[✓]${NC} $1"; }
log_warn() { echo -e "${YELLOW}[!]${NC} $1"; }
log_error() { echo -e "${RED}[✗]${NC} $1"; }
log_step() { echo -e "\n${CYAN}═══════════════════════════════════════════════════${NC}\n${BLUE}►${NC} ${WHITE}$1${NC}\n${CYAN}═══════════════════════════════════════════════════${NC}\n"; }
log_success() { echo -e "${GREEN}✅${NC} $1"; }

if [[ $EUID -ne 0 ]]; then
    log_error "Запустите с правами root: sudo ./06-system-cleanup.sh"
    exit 1
fi

# =============================================================================
# ЗАГРУЗКА КОНФИГУРАЦИИ
# =============================================================================
BACKUP_DIR=$(ls -td /root/backup_* 2>/dev/null | head -1)
LOG_FILE="$BACKUP_DIR/cleanup.log"

# =============================================================================
# РАЗДЕЛ 1: ОЧИСТКА APT КЭША
# =============================================================================
log_step "Раздел 1: Очистка APT кэша"

log_info "Размер до очистки:"
du -sh /var/cache/apt/archives/ 2>/dev/null || echo "не определен"

apt autoremove -y 2>&1 | tee -a "$LOG_FILE"
apt autoclean -y 2>&1 | tee -a "$LOG_FILE"
apt clean -y 2>&1 | tee -a "$LOG_FILE"

log_info "Размер после очистки:"
du -sh /var/cache/apt/archives/ 2>/dev/null || echo "не определен"

log_success "APT кэш очищен"

# =============================================================================
# РАЗДЕЛ 2: ОЧИСТКА ЛОГОВ
# =============================================================================
log_step "Раздел 2: Очистка логов"

log_info "Размер логов до очистки:"
journalctl --disk-usage 2>/dev/null || echo "не определен"

# Очистка по времени (15 дней)
log_info "Очистка логов старше 15 дней..."
journalctl --vacuum-time=15d 2>&1 | tee -a "$LOG_FILE"

# Очистка по размеру (800MB)
log_info "Ограничение размера логов 800MB..."
journalctl --vacuum-size=800M 2>&1 | tee -a "$LOG_FILE"

log_info "Размер логов после очистки:"
journalctl --disk-usage 2>/dev/null || echo "не определен"

log_success "Логи очищены"

# =============================================================================
# РАЗДЕЛ 3: ОЧИСТКА ВРЕМЕННЫХ ФАЙЛОВ
# =============================================================================
log_step "Раздел 3: Очистка временных файлов"

log_info "Удаление файлов из /tmp старше 7 дней..."
find /tmp -type f -atime +7 -delete 2>/dev/null || true
find /tmp -type d -empty -delete 2>/dev/null || true

log_info "Удаление файлов из /var/tmp старше 7 дней..."
find /var/tmp -type f -atime +7 -delete 2>/dev/null || true
find /var/tmp -type d -empty -delete 2>/dev/null || true

log_success "Временные файлы удалены"

# =============================================================================
# РАЗДЕЛ 4: ОЧИСТКА СТАРЫХ БЭКАПОВ
# =============================================================================
log_step "Раздел 4: Очистка старых бэкапов"

# Удаляем бэкапы старше 30 дней
if [ -d /root/backup_* ]; then
    log_info "Поиск бэкапов старше 30 дней..."
    find /root -maxdepth 1 -type d -name "backup_*" -mtime +30 -exec rm -rf {} \; 2>/dev/null || true
    log_success "Старые бэкапы удалены"
fi

# =============================================================================
# РАЗДЕЛ 5: ОЧИСТКА КЭША ПОЛЬЗОВАТЕЛЕЙ
# =============================================================================
log_step "Раздел 5: Очистка кэша пользователей"

for user in $(ls /home/ 2>/dev/null); do
    # Очистка кэша браузеров
    if [ -d "/home/$user/.cache" ]; then
        find "/home/$user/.cache" -type f -atime +30 -delete 2>/dev/null || true
        log_info "Очищен кэш пользователя $user"
    fi
    
    # Очистка корзины
    if [ -d "/home/$user/.local/share/Trash" ]; then
        rm -rf "/home/$user/.local/share/Trash/*" 2>/dev/null || true
        log_info "Очищена корзина пользователя $user"
    fi
done

# =============================================================================
# РАЗДЕЛ 6: ОЧИСТКА КЭША DOCKER
# =============================================================================
log_step "Раздел 6: Очистка кэша Docker"

if command -v docker &>/dev/null; then
    log_info "Проверка использования Docker..."
    
    # Очистка неиспользуемых образов, контейнеров, томов
    docker system prune -a -f 2>&1 | tee -a "$LOG_FILE"
    docker volume prune -f 2>&1 | tee -a "$LOG_FILE"
    
    log_success "Docker очищен"
else
    log_info "Docker не установлен, пропускаем"
fi

# =============================================================================
# РАЗДЕЛ 7: СТАТИСТИКА
# =============================================================================
log_step "Статистика системы"

echo -e "${YELLOW}Использование диска:${NC}"
df -h /

echo -e "\n${YELLOW}Использование памяти:${NC}"
free -h

echo -e "\n${YELLOW}Количество установленных пакетов:${NC}"
dpkg --list 2>/dev/null | wc -l

# =============================================================================
# РАЗДЕЛ 8: СОЗДАНИЕ СКРИПТА АВТОМАТИЧЕСКОЙ ОЧИСТКИ
# =============================================================================
log_step "Раздел 7: Создание скрипта автоматической очистки"

cat > /usr/local/bin/cleanup.sh << 'EOF'
#!/bin/bash
# =============================================================================
# Debian 13 Server - Скрипт автоматической очистки
# =============================================================================
# Запуск: /usr/local/bin/cleanup.sh
# Cron: 0 3 * * 0 /usr/local/bin/cleanup.sh
# =============================================================================

LOG_FILE="/var/log/cleanup.log"

log() {
    echo "[$(date '+%Y-%m-%d %H:%M:%S')] $1" | tee -a "$LOG_FILE"
}

log "=== НАЧАЛО ОЧИСТКИ ==="

# Очистка APT
log "Очистка APT кэша..."
apt clean 2>&1 | tee -a "$LOG_FILE"
apt autoclean 2>&1 | tee -a "$LOG_FILE"

# Очистка логов (30 дней)
log "Очистка логов старше 30 дней..."
journalctl --vacuum-time=30d 2>&1 | tee -a "$LOG_FILE"

# Удаление временных файлов
log "Удаление временных файлов..."
find /tmp -type f -atime +7 -delete 2>/dev/null
find /var/tmp -type f -atime +7 -delete 2>/dev/null

# Очистка Docker (если установлен)
if command -v docker &>/dev/null; then
    log "Очистка Docker..."
    docker system prune -a -f 2>&1 | tee -a "$LOG_FILE"
    docker volume prune -f 2>&1 | tee -a "$LOG_FILE"
fi

# Удаление старых бэкапов
log "Удаление бэкапов старше 30 дней..."
find /root -maxdepth 1 -type d -name "backup_*" -mtime +30 -exec rm -rf {} \; 2>/dev/null

log "=== ОЧИСТКА ЗАВЕРШЕНА ==="
log "Свободное место: $(df -h / | awk 'NR==2 {print $4}')"
echo ""
EOF

chmod +x /usr/local/bin/cleanup.sh
log_success "Скрипт очистки создан: /usr/local/bin/cleanup.sh"

# =============================================================================
# РАЗДЕЛ 9: НАСТРОЙКА CRON
# =============================================================================
log_step "Раздел 9: Настройка автоматической очистки"

# Добавление в cron (еженедельно в воскресенье в 3:00)
if ! grep -q "cleanup.sh" /etc/crontab 2>/dev/null; then
    echo "0 3 * * 0 root /usr/local/bin/cleanup.sh" >> /etc/crontab
    log_success "Cron настроен (каждое воскресенье в 3:00)"
else
    log_info "Cron уже настроен"
fi

# =============================================================================
# ИТОГОВЫЙ ОТЧЕТ
# =============================================================================
log_step "Очистка завершена"

echo -e "${GREEN}✅${NC} Система очищена!"
echo ""
echo -e "${YELLOW}📋 Выполнено:${NC}"
echo "  ✓ Очищен APT кэш"
echo "  ✓ Очищены логи (15 дней, 800MB)"
echo "  ✓ Удалены временные файлы"
echo "  ✓ Удалены старые бэкапы"
echo "  ✓ Очищен кэш пользователей"
echo "  ✓ Очищен Docker (если установлен)"
echo "  ✓ Создан скрипт автоматической очистки"
echo "  ✓ Настроен cron (еженедельно)"
echo ""
echo -e "${CYAN}📁 Скрипт очистки:${NC} /usr/local/bin/cleanup.sh"
echo -e "${CYAN}📄 Лог очистки:${NC} /var/log/cleanup.log"
echo ""
read -p "Нажмите Enter для продолжения..."
